//! Translate the WGSL shaders for each SDL3 GPU backend, from the one WGSL source,
//! using SDL3 GPU's resource conventions:
//! - MSL (Metal), by naga: buffer/texture/sampler slots from 0 per stage;
//! - SPIR-V (Vulkan), by naga: fragment sampled textures in set 2, uniform buffers
//!   in set 3 (a texture and its sampler share one combined-image-sampler binding);
//! - DXIL (Direct3D 12): the SPIR-V above → HLSL by SPIRV-Cross → DXIL by DXC, the
//!   same route as SDL_shadercross. Fragment textures (t0, space2), samplers
//!   (s0, space2), uniform buffers (b0, space3); vertex inputs use TEXCOORD<location>,
//!   SDL's default semantic. naga's own HLSL output cannot be used: it reads
//!   samplers through a sampler heap and an index buffer that SDL never binds.
//!
//! HLSL is generated for every target, so the translation is checked everywhere.
//! DXIL needs DXC (with libdxil/dxil.dll for signing): it is built when the target
//! is Windows, or when BUGATRON_DXC is set. DXC is taken from BUGATRON_DXC, else
//! `dxc` on PATH. Otherwise the DXIL constants are empty and SDL is not offered DXIL.

use naga::back::{msl, spv};
use naga::{ResourceBinding, ShaderStage};
use spirv_cross2::compile::hlsl::{self, BindTarget, RegisterBinding};
use spirv_cross2::spirv::ExecutionModel;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

const SHADERS: &[(&str, &str, &str)] = &[("fixed", "vs_main", "fs_main")];

fn rb(group: u32, binding: u32) -> ResourceBinding {
    ResourceBinding { group, binding }
}

/// SPIR-V → HLSL (shader model 6.0) with SDL3's D3D12 register layout.
fn spirv_to_hlsl(words: &[u32], stage: ExecutionModel) -> String {
    let module = spirv_cross2::Module::from_words(words);
    let mut c = spirv_cross2::Compiler::<spirv_cross2::targets::Hlsl>::new(module).expect("SPIRV-Cross: parse");
    if stage == ExecutionModel::Fragment {
        let reg = |register, space| Some(RegisterBinding { register, space });
        let tex = BindTarget { srv: reg(0, 2), sampler: reg(0, 2), cbv: None, uav: None };
        c.add_resource_binding(stage, hlsl::ResourceBinding::from_qualified(2, 0), &tex).expect("SPIRV-Cross: texture binding");
        let ubo = BindTarget { cbv: reg(0, 3), srv: None, sampler: None, uav: None };
        c.add_resource_binding(stage, hlsl::ResourceBinding::from_qualified(3, 0), &ubo).expect("SPIRV-Cross: uniform binding");
    }
    let mut opts = hlsl::CompilerOptions::default();
    opts.shader_model = hlsl::HlslShaderModel::ShaderModel6_0;
    c.compile(&opts).expect("SPIRV-Cross: HLSL").to_string()
}

/// DXC, if DXIL is wanted for this build.
fn dxc() -> Option<PathBuf> {
    println!("cargo:rerun-if-env-changed=BUGATRON_DXC");
    if let Some(p) = std::env::var_os("BUGATRON_DXC") {
        return Some(PathBuf::from(p));
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return None;
    }
    let ok = Command::new("dxc").arg("--version").output().is_ok_and(|o| o.status.success());
    if !ok {
        panic!("Building for Windows needs DXC for the Direct3D 12 shaders: put `dxc` on PATH or set BUGATRON_DXC \
                (Windows SDK, or https://github.com/microsoft/DirectXShaderCompiler/releases; the Linux release works too).");
    }
    Some(PathBuf::from("dxc"))
}

/// HLSL → signed DXIL.
fn hlsl_to_dxil(dxc: &Path, hlsl: &Path, profile: &str, dxil: &Path) {
    let o = Command::new(dxc)
        .args(["-T", profile, "-E", "main", "-Fo"]).arg(dxil).arg(hlsl)
        .output()
        .unwrap_or_else(|e| panic!("running DXC ({}): {e}", dxc.display()));
    if !o.status.success() {
        panic!("DXC failed on {}:\n{}{}", hlsl.display(), String::from_utf8_lossy(&o.stdout), String::from_utf8_lossy(&o.stderr));
    }
}

fn main() {
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let mut rs = String::from("// Generated by build.rs from shaders/*.wgsl.\n");
    let dxc = dxc();
    for &(name, vs, fs) in SHADERS {
        let path = format!("shaders/{name}.wgsl");
        println!("cargo:rerun-if-changed={path}");
        let src = std::fs::read_to_string(&path).unwrap();
        let module = naga::front::wgsl::parse_str(&src).unwrap_or_else(|e| panic!("{path}: {}", e.emit_to_string(&src)));
        let info = naga::valid::Validator::new(naga::valid::ValidationFlags::all(), naga::valid::Capabilities::empty())
            .validate(&module)
            .unwrap_or_else(|e| panic!("{path}: {e:?}"));

        // MSL
        let mut fs_res = msl::EntryPointResources::default();
        fs_res.resources.insert(rb(3, 0), msl::BindTarget { buffer: Some(0), ..Default::default() });
        fs_res.resources.insert(rb(2, 0), msl::BindTarget { texture: Some(0), ..Default::default() });
        fs_res.resources.insert(rb(2, 1), msl::BindTarget { sampler: Some(msl::BindSamplerTarget::Resource(0)), ..Default::default() });
        let mut opts = msl::Options { lang_version: (2, 1), ..Default::default() };
        opts.per_entry_point_map.insert(vs.to_string(), msl::EntryPointResources::default());
        opts.per_entry_point_map.insert(fs.to_string(), fs_res);
        for (stage, entry) in [(ShaderStage::Vertex, vs), (ShaderStage::Fragment, fs)] {
            let popts = msl::PipelineOptions { entry_point: Some((stage, entry.to_string())), ..Default::default() };
            let (code, tinfo) = msl::write_string(&module, &info, &opts, &popts).unwrap_or_else(|e| panic!("{path} {entry} MSL: {e:?}"));
            let ep = tinfo.entry_point_names.iter().find_map(|n| n.as_ref().ok().cloned()).expect("entry point");
            let file = format!("{name}_{entry}.msl");
            std::fs::write(out.join(&file), code).unwrap();
            let up = format!("{}_{}", name.to_uppercase(), entry.to_uppercase());
            writeln!(rs, "pub const {up}_MSL: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/{file}\"));").unwrap();
            writeln!(rs, "pub const {up}_MSL_ENTRY: &str = \"{ep}\";").unwrap();
        }

        // SPIR-V
        let mut sopts = spv::Options::default();
        sopts.binding_map.insert(rb(3, 0), spv::BindingInfo { descriptor_set: 3, binding: 0, binding_array_size: None });
        sopts.binding_map.insert(rb(2, 0), spv::BindingInfo { descriptor_set: 2, binding: 0, binding_array_size: None });
        sopts.binding_map.insert(rb(2, 1), spv::BindingInfo { descriptor_set: 2, binding: 0, binding_array_size: None });
        sopts.flags.remove(spv::WriterFlags::DEBUG);
        // SDL's Vulkan backend already flips the viewport so clip space is Y-up on
        // every backend (as on Metal); naga's own Y flip would turn images upside down.
        sopts.flags.remove(spv::WriterFlags::ADJUST_COORDINATE_SPACE);
        for (stage, entry) in [(ShaderStage::Vertex, vs), (ShaderStage::Fragment, fs)] {
            let popts = spv::PipelineOptions { shader_stage: stage, entry_point: entry.to_string() };
            let words = spv::write_vec(&module, &info, &sopts, Some(&popts)).unwrap_or_else(|e| panic!("{path} {entry} SPIR-V: {e:?}"));
            let bytes: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
            let file = format!("{name}_{entry}.spv");
            std::fs::write(out.join(&file), bytes).unwrap();
            let up = format!("{}_{}", name.to_uppercase(), entry.to_uppercase());
            writeln!(rs, "pub const {up}_SPV: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\"));").unwrap();

            // HLSL and DXIL, from this SPIR-V
            let (model, profile) = match stage {
                ShaderStage::Vertex => (ExecutionModel::Vertex, "vs_6_0"),
                _ => (ExecutionModel::Fragment, "ps_6_0"),
            };
            let hlsl_file = format!("{name}_{entry}.hlsl");
            std::fs::write(out.join(&hlsl_file), spirv_to_hlsl(&words, model)).unwrap();
            writeln!(rs, "pub const {up}_HLSL: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/{hlsl_file}\"));").unwrap();
            if let Some(dxc) = &dxc {
                let file = format!("{name}_{entry}.dxil");
                hlsl_to_dxil(dxc, &out.join(&hlsl_file), profile, &out.join(&file));
                writeln!(rs, "pub const {up}_DXIL: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\"));").unwrap();
            } else {
                writeln!(rs, "pub const {up}_DXIL: &[u8] = &[];").unwrap();
            }
        }
    }
    std::fs::write(out.join("shaders.rs"), rs).unwrap();
}
